async (page) => {
  const results = [];
  const assertFrame = async (device) => {
    await page.locator('[data-preview-device="' + device + '"]').waitFor();
    await page.getByRole('dialog').evaluate(async el => {
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
      await Promise.all(el.closest('.ant-drawer').getAnimations({ subtree: true }).filter(a => a.effect.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {})));
    });
    if (await page.getByRole('dialog').locator('iframe').count()) await page.getByRole('dialog').frameLocator('iframe').locator('h1').waitFor();
    const sizes = await page.getByRole('dialog').evaluate(dialog => Array.from(dialog.querySelectorAll('.ant-drawer-body,.material-preview-toolbar,.material-preview-stage,.material-device__screen')).map(el => ({ name: el.className, width: el.clientWidth, scroll: el.scrollWidth })));
    if (sizes.some(size => size.scroll > size.width + 1)) throw new Error('Horizontal overflow: ' + JSON.stringify(sizes));
    results.push({ device, viewport: page.viewportSize(), overflow: false });
  };
  const open = async (name) => page.getByRole('row').filter({ hasText: name }).getByRole('button').last().click();
  const close = async () => { const dialog = page.getByRole('dialog'); await dialog.getByRole('button', { name: '关闭', exact: true }).click(); await dialog.waitFor({ state: 'hidden' }); };
  if (await page.getByRole('dialog').count()) await close();
  await open('会员专属礼遇 · 邮件');
  await assertFrame('ios');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-email.png' });
  const selector = page.getByRole('combobox', { name: '邮件客户端预览' });
  await selector.selectOption('email_android');
  await assertFrame('android');
  await selector.selectOption('email_desktop');
  await assertFrame('desktop');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-email-pc.png' });
  await selector.selectOption('h5');
  await assertFrame('h5');
  if (await page.locator('iframe').getAttribute('sandbox') !== '') throw new Error('HTML sandbox missing');
  await close();
  await open('会员专属礼遇 · H5');
  await assertFrame('h5');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-h5.png' });
  await close();
  await open('会员专属礼遇 · WhatsApp');
  await assertFrame('ios');
  await page.getByRole('combobox', { name: '客户端预览', exact: true }).selectOption('whatsapp_web');
  await assertFrame('desktop');
  if (await page.locator('[data-preview-device]').count() !== 1) throw new Error('Nested devices in desktop preview');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-chat-pc.png' });
  await page.getByRole('combobox', { name: '客户端预览', exact: true }).selectOption('whatsapp_android');
  await assertFrame('android');
  await close();
  await open('会员专属礼遇 · 短信');
  await assertFrame('android');
  await page.getByRole('button', { name: 'iOS', exact: true }).click();
  await assertFrame('ios');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-sms.png' });
  await close();
  await open('会员专属礼遇 · 推送');
  await assertFrame('android');
  await page.getByRole('button', { name: 'iOS', exact: true }).click();
  await assertFrame('ios');
  await page.getByRole('dialog').screenshot({ path: 'output/playwright/material-preview-ios.png' });
  await page.setViewportSize({ width: 375, height: 900 });
  await assertFrame('ios');
  await page.screenshot({ path: 'output/playwright/material-preview-375.png' });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await close();
  await page.getByRole('searchbox', { name: '按名称搜索' }).fill('no-matching-material');
  if (await page.getByRole('row').filter({ hasText: '会员专属礼遇' }).count()) throw new Error('Filtered empty state failed');
  await page.getByRole('searchbox', { name: '按名称搜索' }).fill('');
  return results;
}
